import { expect, test } from '@playwright/test';
import { adminEmail, adminPassword, apiUrl, createUser, headersFor, login, openSection, tokenFor, uniqueName } from './helpers.js';

test('event links and private feeds enforce access, revocation, updates and cancellations', async ({ request }) => {
  const owner = await createUser(request, 'calowner');
  const guest = await createUser(request, 'calguest');
  const stranger = await createUser(request, 'calother');
  const headers = headersFor(owner.username);
  const data = { title: uniqueName('Shared planning'), description: 'Agenda; one,two', startDate: '2026-12-10', endDate: '2026-12-10', start: '09:00', end: '10:00', allDay: false, people: [guest.id], timeZoneId: 'Asia/Bangkok' };
  const created = await request.post(`${apiUrl}/api/meetings?username=${owner.username}`, { headers, data });
  expect(created.ok(), await created.text()).toBeTruthy();
  const meeting = await created.json();
  const base = `${apiUrl}/api/calendar`;
  const share = `${base}/meetings/${meeting.id}/share`;
  const privateIcs = `${base}/meetings/${meeting.id}/calendar.ics`;
  expect((await request.get(privateIcs)).status()).toBe(401);
  expect((await request.get(privateIcs, { headers: headersFor(stranger.username) })).status()).toBe(404);
  expect((await request.get(privateIcs, { headers: headersFor(guest.username) })).ok()).toBeTruthy();
  expect((await request.post(share, { headers: headersFor(guest.username), data: { action: 'enable' } })).status()).toBe(404);
  const enabled = await request.post(share, { headers, data: { action: 'enable' } });
  expect(enabled.ok(), await enabled.text()).toBeTruthy();
  const { token } = await enabled.json();
  const publicEvent = await request.get(`${base}/events/${token}`);
  expect(publicEvent.ok(), await publicEvent.text()).toBeTruthy();
  expect(publicEvent.headers()['cache-control']).toBe('no-store');
  const details = await publicEvent.json();
  expect(details.calendarStart).toBe('2026-12-10T02:00:00Z');
  expect(details).not.toHaveProperty('people');
  expect(details).not.toHaveProperty('organizerUserId');
  const ics = await request.get(`${base}/events/${token}/calendar.ics`);
  expect(ics.headers()['content-type']).toContain('text/calendar');
  expect(await ics.text()).toContain('DTSTART:20261210T020000Z');
  const subscription = await request.post(`${base}/subscription`, { headers: headersFor(guest.username), data: { action: 'enable' } });
  expect(subscription.ok(), await subscription.text()).toBeTruthy();
  const { token: feedToken } = await subscription.json();
  const feed = `${base}/feeds/${feedToken}/calendar.ics`;
  expect(await (await request.get(feed)).text()).toContain(`UID:${meeting.id}@huddle`);
  const ownPrivate = await request.post(`${apiUrl}/api/meetings?username=${owner.username}`, { headers, data: { ...data, title: 'Private unrelated meeting', people: [] } });
  expect(ownPrivate.ok()).toBeTruthy();
  expect(await (await request.get(feed)).text()).not.toContain('Private unrelated meeting');
  const removable = await request.post(`${apiUrl}/api/meetings?username=${owner.username}`, { headers, data: { ...data, title: 'Removed invitation' } });
  expect(removable.ok()).toBeTruthy();
  const removedId = (await removable.json()).id;
  expect(await (await request.get(feed)).text()).toContain(`UID:${removedId}@huddle`);
  const removeGuest = await request.put(`${apiUrl}/api/meetings/${removedId}?username=${owner.username}`, { headers, data: { ...data, people: [] } });
  expect(removeGuest.ok()).toBeTruthy();
  expect(await (await request.get(feed)).text()).not.toContain(`UID:${removedId}@huddle`);
  expect((await request.get(`${base}/meetings/${removedId}/calendar.ics`, { headers: headersFor(guest.username) })).status()).toBe(404);
  const update = await request.put(`${apiUrl}/api/meetings/${meeting.id}?username=${owner.username}`, { headers, data: { ...data, start: '11:00', end: '12:00' } });
  expect(update.ok(), await update.text()).toBeTruthy();
  expect(await (await request.get(feed)).text()).toContain('DTSTART:20261210T040000Z');
  const cancelled = await request.post(`${apiUrl}/api/meetings/${meeting.id}/cancel?username=${owner.username}`, { headers });
  expect(cancelled.ok(), await cancelled.text()).toBeTruthy();
  const cancellation = await (await request.get(feed)).text();
  expect(cancellation).toContain(`UID:${meeting.id}@huddle`);
  expect(cancellation).toContain('STATUS:CANCELLED');
  expect(cancellation).toContain('SEQUENCE:2');
  const rotated = await request.post(share, { headers, data: { action: 'regenerate' } });
  const { token: newToken } = await rotated.json();
  expect((await request.get(`${base}/events/${token}`)).status()).toBe(404);
  expect((await request.get(`${base}/events/${newToken}`)).ok()).toBeTruthy();
  await request.post(share, { headers, data: { action: 'disable' } });
  expect((await request.get(`${base}/events/${newToken}/calendar.ics`)).status()).toBe(404);
  const rotatedFeed = await request.post(`${base}/subscription`, { headers: headersFor(guest.username), data: { action: 'regenerate' } });
  const { token: nextFeed } = await rotatedFeed.json();
  expect((await request.get(feed)).status()).toBe(404);
  await request.post(`${base}/subscription`, { headers: headersFor(guest.username), data: { action: 'disable' } });
  expect((await request.get(`${base}/feeds/${nextFeed}/calendar.ics`)).status()).toBe(404);
  expect((await request.post(`${apiUrl}/api/meetings?username=${owner.username}`, { headers, data: { ...data, timeZoneId: 'Invalid/Zone' } })).status()).toBe(400);
  expect((await request.post(`${apiUrl}/api/meetings?username=${owner.username}`, { headers, data: { ...data, start: '24:00' } })).status()).toBe(400);
  const ownerSubscription = await request.post(`${base}/subscription`, { headers, data: { action: 'enable' } });
  const ownerFeedToken = (await ownerSubscription.json()).token;
  const reenabled = await request.post(share, { headers, data: { action: 'enable' } });
  const reenabledToken = (await reenabled.json()).token;
  const adminToken = await tokenFor(request, adminEmail, adminPassword);
  const disabled = await request.patch(`${apiUrl}/api/admin/users/${owner.id}/enabled`, { headers: { Authorization: `Bearer ${adminToken}` }, data: { isEnabled: false } });
  expect(disabled.ok(), await disabled.text()).toBeTruthy();
  expect((await request.get(`${base}/events/${reenabledToken}`)).status()).toBe(404);
  expect((await request.get(`${base}/feeds/${ownerFeedToken}/calendar.ics`)).status()).toBe(404);
});

test('sharing dialogs and public page work with keyboard cancellation and subscription settings', async ({ page, request, context }) => {
  const owner = await createUser(request, 'calui');
  await login(page, owner.username);
  await openSection(page, 'Meetings');
  await page.getByRole('button', { name: 'New meeting', exact: true }).click();
  const form = page.getByRole('dialog', { name: 'New meeting', exact: true });
  const title = uniqueName('Public event');
  await form.getByLabel('Title', { exact: true }).fill(title);
  await form.getByLabel('Time zone', { exact: true }).fill('Asia/Bangkok');
  await form.getByRole('button', { name: 'Create meeting' }).click();
  await page.getByRole('button', { name: 'Share event', exact: true }).click();
  const sharing = page.getByRole('dialog', { name: 'Share event', exact: true });
  await sharing.getByRole('button', { name: 'Enable event sharing' }).click();
  const eventUrl = await sharing.getByLabel('Event link').inputValue();
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await sharing.getByRole('button', { name: 'Copy link' }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(eventUrl);
  await expect(sharing.locator('.app-modal-header')).toBeVisible();
  await expect(sharing.locator('.app-modal-footer')).toBeVisible();
  await page.screenshot({ path: 'test-results/calendar-sharing-dialog.png' });
  const publicPage = await context.newPage();
  await publicPage.goto(eventUrl);
  await expect(publicPage.getByRole('heading', { name: title })).toBeVisible();
  await expect(publicPage.getByRole('link', { name: 'Add to Google Calendar' })).toHaveAttribute('href', /calendar.google.com/);
  await expect(publicPage.getByText('Time zone: Asia/Bangkok')).toBeVisible();
  await publicPage.screenshot({ path: 'test-results/calendar-public-event.png' });
  await publicPage.setViewportSize({ width: 390, height: 844 });
  await expect(publicPage.locator('body')).toHaveJSProperty('scrollWidth', 390);
  await publicPage.evaluate(() => { document.documentElement.dataset.theme = 'dark'; });
  await publicPage.screenshot({ path: 'test-results/calendar-public-event-mobile-dark.png' });
  await publicPage.close();
  await page.keyboard.press('Escape');
  await expect(sharing).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Share event', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Subscribe to calendar', exact: true }).click();
  const settings = page.getByRole('dialog', { name: 'Subscribe to calendar', exact: true });
  await settings.getByRole('button', { name: 'Enable subscription' }).click();
  const original = await settings.getByLabel('Subscription URL').inputValue();
  await settings.getByRole('button', { name: 'Regenerate link' }).click();
  await page.keyboard.press('Escape');
  await expect(settings.getByLabel('Subscription URL')).toHaveValue(original);
  await settings.getByRole('button', { name: 'Disable link' }).click();
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(settings.getByText('Sharing is disabled.')).toBeVisible();
  expect((await request.get(original)).status()).toBe(404);
});
